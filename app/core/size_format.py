from __future__ import annotations

from decimal import Decimal

from app.models.enums import SizeFormat

# ตาราง mapping ของ ADR-0009 D16 — **เปิด ไม่ใช่ปิด**: เพิ่มขนาดใหม่ได้
# แต่ต้องเพิ่ม **พร้อม unit test ในรอบเดียวกัน** (D4 บังคับว่ามีเทส)
#
# 🔴 `27 × 41` map เป็น `ONE_SHEET` เหมือน `27 × 40` แต่ **ห้ามทิ้งตัวเลขที่วัดได้**
# เพราะ 27×41 เป็น *สัญญาณของงานพิมพ์ยุคเก่า* — ข้อมูลที่มีค่าที่สุดของใบนั้น
# อยู่ที่ตัวเลข ไม่ใช่ที่คำว่า ONE_SHEET · นั่นคือเหตุผลที่ `width_in`/`height_in`
# เป็นคอลัมน์จริง ไม่ใช่ตัวแปรชั่วคราวระหว่างทางไปหา `size_format`
_MEASURED_TO_FORMAT: dict[tuple[Decimal, Decimal], SizeFormat] = {
    (Decimal("27"), Decimal("40")): SizeFormat.ONE_SHEET,
    (Decimal("27"), Decimal("41")): SizeFormat.ONE_SHEET,
}


def derive_size_format(
    width_in: Decimal | None, height_in: Decimal | None
) -> SizeFormat | None:
    """คืน `size_format` จากขนาดที่วัดได้ — `None` เมื่อยังวัดไม่ครบทั้งสองด้าน

    🔴 **ขาดด้านใดด้านหนึ่ง = `None` ไม่ใช่ `OTHER`** — `OTHER` แปลว่า *วัดแล้ว
    ไม่เข้าสเกล* การคืนมันตอนที่ยังวัดไม่ครบคือการอ้างว่ามีการวัดที่ไม่เคยเกิดขึ้น
    · และ **ห้ามเดาด้านที่ขาดจากอัตราส่วนของอีกด้าน** (ADR-0009 D16) — อัตราส่วน
    ของ 27×40 กับ 27×41 ต่างกันไม่ถึง 3% การเดาจะกลืนความต่างที่ทั้งข้อนี้มีไว้เพื่อรักษา

    `Decimal("27.0")` กับ `Decimal("27")` ต้องให้ผลเท่ากัน — `Decimal.__eq__`
    เทียบเชิงตัวเลข (ไม่ใช่เชิงตัวอักษร) แต่ `hash()`/การค้น dict ก็ตรงกันด้วย
    เพราะ Python รับประกันว่า `a == b` แล้ว `hash(a) == hash(b)` สำหรับ Decimal
    — จึงค้น `_MEASURED_TO_FORMAT` ตรง ๆ ได้โดยไม่ต้อง normalize ก่อน
    """
    if width_in is None or height_in is None:
        return None
    return _MEASURED_TO_FORMAT.get((width_in, height_in), SizeFormat.OTHER)
